function [y cb cr]=rgb2ycbcr(f)
r=f(:,:,1);
g=f(:,:,2);
b=f(:,:,3);

y=zeros(size(f(:,:,1)));
cb=zeros(size(f(:,:,1)));
cr=zeros(size(f(:,:,1)));

y=0.299*r + 0.587*g + 0.114*b;
cb=-0.1687*r -0.3313*g -0.5*b+ 128*1;
cr=0.5*r -0.4187*g -0.0813*b + 128*1;

% Y = 0.2990*R + 0.5870*G + 0.1140*B;
% Cb = 0.1687*R + 0.3312*G + 0.5000*B; 
% Cr = 0.5000*R + 0.4186*G + 0.0813*B;
end